package io.github.khaledamiri.mcpdiscovery.client.boot;

import java.time.Duration;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import io.github.khaledamiri.mcpdiscovery.registry.InstanceStatus;

/**
 * Configuration of the MCP Discovery client, bound to {@code mcp-discovery.client.*}.
 *
 * <pre>
 * discovery:
 *   client:
 *     registry-url: http://localhost:8761
 *     api-key: ${MCP_DISCOVERY_API_KEY}
 *     server-name: jira-mcp
 * </pre>
 */
public class McpDiscoveryClientProperties {

    /** Create the client at all. */
    private boolean enabled = true;

    /** Register this application in the registry. Set to false for agents that only search. */
    private boolean register = true;

    /** Base URL of the registry. */
    private String registryUrl = "http://localhost:8761";

    /** Shared secret sent as X-Mcp-Discovery-Key. */
    private String apiKey;

    /** Logical server name. Defaults to spring.application.name. */
    private String serverName;

    /** Stable instance id. Generated by the registry when empty. */
    private String instanceId;

    /** Full MCP endpoint advertised to agents. Derived from host, port and path when empty. */
    private String endpoint;

    /** Host used to derive the endpoint. Defaults to the first non-loopback address. */
    private String hostname;

    /** When deriving the host, use the IP address rather than the host name. */
    private boolean preferIpAddress = true;

    /** Scheme used to derive the endpoint. */
    private String scheme = "http";

    /** Path of the MCP endpoint, used to derive the endpoint. */
    private String path = "/mcp";

    /** Server version. */
    private String version;

    /** Status sent at registration. */
    private InstanceStatus initialStatus = InstanceStatus.UP;

    /** Free-form metadata. Readable by every registry client: never put secrets here. */
    private Map<String, String> metadata = new LinkedHashMap<>();

    /** Tools declared at registration. Optional when the registry probes servers. */
    private List<Tool> tools = new ArrayList<>();

    /** HTTP timeout of registry requests. */
    private Duration timeout = Duration.ofSeconds(10);

    /** Overrides the heartbeat interval suggested by the registry. */
    private Duration heartbeatInterval;

    /** Delay between registration attempts while the registry is unreachable. */
    private Duration retryInterval = Duration.ofSeconds(30);

    /** A tool declared in configuration. */
    public static class Tool {
        /** Tool name, as passed to tools/call. */
        private String name;
        /** Optional human-readable title. */
        private String title;
        /** Description used by tool search. */
        private String description;
        /** JSON Schema of the arguments. */
        private Map<String, Object> inputSchema = new LinkedHashMap<>();

        /** @return the tool name */
        public String getName() { return name; }
        /** @param name the tool name */
        public void setName(String name) { this.name = name; }
        /** @return the title */
        public String getTitle() { return title; }
        /** @param title the title */
        public void setTitle(String title) { this.title = title; }
        /** @return the description */
        public String getDescription() { return description; }
        /** @param description the description */
        public void setDescription(String description) { this.description = description; }
        /** @return the input schema */
        public Map<String, Object> getInputSchema() { return inputSchema; }
        /** @param inputSchema the input schema */
        public void setInputSchema(Map<String, Object> inputSchema) { this.inputSchema = inputSchema; }
    }

    /** @return whether the client is enabled */
    public boolean isEnabled() { return enabled; }
    /** @param enabled whether the client is enabled */
    public void setEnabled(boolean enabled) { this.enabled = enabled; }
    /** @return whether to register this application */
    public boolean isRegister() { return register; }
    /** @param register whether to register this application */
    public void setRegister(boolean register) { this.register = register; }
    /** @return the registry URL */
    public String getRegistryUrl() { return registryUrl; }
    /** @param registryUrl the registry URL */
    public void setRegistryUrl(String registryUrl) { this.registryUrl = registryUrl; }
    /** @return the API key */
    public String getApiKey() { return apiKey; }
    /** @param apiKey the API key */
    public void setApiKey(String apiKey) { this.apiKey = apiKey; }
    /** @return the server name */
    public String getServerName() { return serverName; }
    /** @param serverName the server name */
    public void setServerName(String serverName) { this.serverName = serverName; }
    /** @return the instance id */
    public String getInstanceId() { return instanceId; }
    /** @param instanceId the instance id */
    public void setInstanceId(String instanceId) { this.instanceId = instanceId; }
    /** @return the endpoint */
    public String getEndpoint() { return endpoint; }
    /** @param endpoint the endpoint */
    public void setEndpoint(String endpoint) { this.endpoint = endpoint; }
    /** @return the hostname */
    public String getHostname() { return hostname; }
    /** @param hostname the hostname */
    public void setHostname(String hostname) { this.hostname = hostname; }
    /** @return whether to prefer the IP address */
    public boolean isPreferIpAddress() { return preferIpAddress; }
    /** @param preferIpAddress whether to prefer the IP address */
    public void setPreferIpAddress(boolean preferIpAddress) { this.preferIpAddress = preferIpAddress; }
    /** @return the scheme */
    public String getScheme() { return scheme; }
    /** @param scheme the scheme */
    public void setScheme(String scheme) { this.scheme = scheme; }
    /** @return the endpoint path */
    public String getPath() { return path; }
    /** @param path the endpoint path */
    public void setPath(String path) { this.path = path; }
    /** @return the version */
    public String getVersion() { return version; }
    /** @param version the version */
    public void setVersion(String version) { this.version = version; }
    /** @return the initial status */
    public InstanceStatus getInitialStatus() { return initialStatus; }
    /** @param initialStatus the initial status */
    public void setInitialStatus(InstanceStatus initialStatus) { this.initialStatus = initialStatus; }
    /** @return the metadata */
    public Map<String, String> getMetadata() { return metadata; }
    /** @param metadata the metadata */
    public void setMetadata(Map<String, String> metadata) { this.metadata = metadata; }
    /** @return the declared tools */
    public List<Tool> getTools() { return tools; }
    /** @param tools the declared tools */
    public void setTools(List<Tool> tools) { this.tools = tools; }
    /** @return the HTTP timeout */
    public Duration getTimeout() { return timeout; }
    /** @param timeout the HTTP timeout */
    public void setTimeout(Duration timeout) { this.timeout = timeout; }
    /** @return the heartbeat interval override */
    public Duration getHeartbeatInterval() { return heartbeatInterval; }
    /** @param heartbeatInterval the heartbeat interval override */
    public void setHeartbeatInterval(Duration heartbeatInterval) { this.heartbeatInterval = heartbeatInterval; }
    /** @return the retry interval */
    public Duration getRetryInterval() { return retryInterval; }
    /** @param retryInterval the retry interval */
    public void setRetryInterval(Duration retryInterval) { this.retryInterval = retryInterval; }
}
