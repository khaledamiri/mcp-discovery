package io.github.khaledamiri.mcpdiscovery.client;

import java.time.Duration;
import java.util.concurrent.ScheduledFuture;

import io.github.khaledamiri.mcpdiscovery.registry.RegistrationRequest;

/**
 * An active registration. Heartbeats are sent in the background until {@link #close()} is
 * called, which also deregisters the instance.
 */
public final class Registration implements AutoCloseable {

    private final McpDiscoveryClient client;
    private final RegistrationRequest request;
    private final Duration heartbeatInterval;
    private volatile ScheduledFuture<?> heartbeat;
    private volatile boolean closed;

    Registration(McpDiscoveryClient client, RegistrationRequest request, Duration heartbeatInterval) {
        this.client = client;
        this.request = request;
        this.heartbeatInterval = heartbeatInterval;
    }

    /** @return the logical server name */
    public String serverName() {
        return request.serverName();
    }

    /** @return the instance id (generated by the registry when none was given) */
    public String instanceId() {
        return request.instanceId();
    }

    /** @return the interval between heartbeats */
    public Duration heartbeatInterval() {
        return heartbeatInterval;
    }

    /** @return true once {@link #close()} was called */
    public boolean isClosed() {
        return closed;
    }

    RegistrationRequest request() {
        return request;
    }

    void heartbeat(ScheduledFuture<?> future) {
        this.heartbeat = future;
    }

    /** Stops heartbeats and deregisters the instance. Errors while deregistering are ignored. */
    @Override
    public void close() {
        if (closed) {
            return;
        }
        closed = true;
        ScheduledFuture<?> future = heartbeat;
        if (future != null) {
            future.cancel(false);
        }
        client.deregister(this);
    }
}
